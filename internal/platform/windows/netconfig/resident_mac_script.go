// ResidentVirtualHostMacScript configures only the newly held physical Mac
// Wintun. Fixed firewall plans are appended by the caller to this one execution.
// dadZeroFresh is a current native readback, never a stored optimization flag.
func ResidentVirtualHostMacScript(index uint32, guid string, mtu int, proofs []usbaddress.InterfaceProof, dadZeroFresh bool) (string, error) {
	if index == 0 || guid != "{A4611646-E050-4D25-B83E-633A5598F302}" || mtu < 576 || mtu > 1500 {
		return "", fmt.Errorf("resident Mac adapter plan invalid")
	}
	hasHost := false
	for _, p := range proofs {
		if p.Role == "host" && p.Created > 0 {
			hasHost = true
		}
	}
	if !hasHost {
		return "", fmt.Errorf("shared host address unproven")
	}
	conflict, err := usbaddress.ConflictScript(index, guid, proofs)
	if err != nil {
		return "", err
	}
	check := fmt.Sprintf(`$ErrorActionPreference='Stop';$a=@(Get-NetAdapter -IncludeHidden | Where-Object {$_.ifIndex -eq %d});if($a.Count -ne 1 -or [guid]$a[0].InterfaceGuid -ne [guid]'%s' -or $a[0].Name -cne 'USB Link'){throw 'Owned adapter identity mismatch'};`, index, guid)
	script := check + conflict + fmt.Sprintf(`
Set-NetIPInterface -InterfaceIndex %d -AddressFamily IPv4 -Dhcp Disabled -NlMtuBytes %d -InterfaceMetric 5000 -PolicyStore ActiveStore;
Set-NetIPInterface -InterfaceIndex %d -AddressFamily IPv4 -WeakHostSend Enabled -WeakHostReceive Enabled -Forwarding Enabled -PolicyStore ActiveStore;
New-NetIPAddress -InterfaceIndex %d -IPAddress '10.6.9.253' -SkipAsSource $true -PrefixLength 32 -AddressFamily IPv4 -PolicyStore ActiveStore | Out-Null;
New-NetRoute -InterfaceIndex %d -DestinationPrefix '10.6.9.2/32' -NextHop '0.0.0.0' -RouteMetric 5000 -PolicyStore ActiveStore | Out-Null;
`, index, mtu, index, index, index)
	if dadZeroFresh {
		script += fmt.Sprintf(`$ip=@(Get-NetIPAddress -InterfaceIndex %d -IPAddress '10.6.9.253' -ErrorAction Stop);if($ip.Count -ne 1 -or $ip[0].AddressState -ne 'Preferred'){throw 'IPv4 address not ready after verified DadTransmits zero'};`, index)
	} else {
		script += fmt.Sprintf(`$deadline=(Get-Date).AddSeconds(15);do{$ip=Get-NetIPAddress -InterfaceIndex %d -IPAddress '10.6.9.253';if($ip.AddressState -eq 'Duplicate'){throw 'Duplicate test address'};if($ip.AddressState -eq 'Preferred'){break};Start-Sleep -Milliseconds 200}while((Get-Date) -lt $deadline);if($ip.AddressState -ne 'Preferred'){throw 'IPv4 address not ready'};`, index)
	}
	script += fmt.Sprintf(`$flags=Get-NetIPInterface -InterfaceIndex %d -AddressFamily IPv4 -PolicyStore ActiveStore;if($flags.WeakHostSend -ne 'Enabled' -or $flags.WeakHostReceive -ne 'Enabled' -or $flags.Forwarding -ne 'Enabled'){throw 'USB local delivery flags changed'};Write-Output 'USB_LOCAL_DELIVERY_FLAGS_VERIFIED';`, index)
	// Preserve the existing optional NLA-profile behavior without a second
	// process after peer detection. Interface-scoped rules apply with no NLA row.
	script += "try{" + PrivateProfileScript(index, guid) + "}catch{Write-Output 'USB_PRIVATE_PROFILE_WARNING scoped_rules_remain_active'};"
	return script, nil
}

// This accepts only the exact wait block generated by the old Mac scripts.
// The caller must supply this invocation's successful native Dad0 readback.
func UseFreshDADZeroMacWait(script string, index uint32, shared bool) (string, error) {
	if index == 0 {
		return "", fmt.Errorf("invalid Mac wait scope")
	}
	address := "10.6.9.1"
	if shared {
		address = "10.6.9.253"
	}
	old := fmt.Sprintf("$deadline=(Get-Date).AddSeconds(15); do {$ip=Get-NetIPAddress -InterfaceIndex %d -IPAddress '%s'; if($ip.AddressState -eq 'Duplicate'){throw 'Duplicate test address'}; if($ip.AddressState -eq 'Preferred'){break}; Start-Sleep -Milliseconds 200} while((Get-Date) -lt $deadline); if($ip.AddressState -ne 'Preferred'){throw 'IPv4 address not ready'};", index, address)
	if strings.Count(script, old) != 1 {
		return "", fmt.Errorf("generated Mac address wait changed")
	}
	fresh := fmt.Sprintf("$ip=@(Get-NetIPAddress -InterfaceIndex %d -IPAddress '%s' -ErrorAction Stop);if($ip.Count -ne 1 -or $ip[0].AddressState -ne 'Preferred'){throw 'IPv4 address not ready after verified DadTransmits zero'};", index, address)
	return strings.Replace(script, old, fresh, 1), nil
}
